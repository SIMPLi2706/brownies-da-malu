-- 1. TABELA DE PERFIS DE USUÁRIOS (CADASTRO COMPLETO)
create table if not exists public.perfis (
  id uuid references auth.users on delete cascade primary key,
  nome text not null,
  telefone text not null,
  endereco text,
  numero text,
  bairro text,
  cidade text default 'Porto Velho - RO',
  ponto_referencia text,
  criado_em timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ativar segurança em nível de linha (RLS)
alter table public.perfis enable row level security;

-- Políticas de segurança para Perfis
drop policy if exists "Usuários podem ver seu próprio perfil" on public.perfis;
create policy "Usuários podem ver seu próprio perfil"
  on public.perfis for select
  using (auth.uid() = id or auth.uid() is null);

drop policy if exists "Usuários podem criar seu próprio perfil" on public.perfis;
create policy "Usuários podem criar seu próprio perfil"
  on public.perfis for insert
  with check (true);

drop policy if exists "Usuários podem atualizar seu próprio perfil" on public.perfis;
create policy "Usuários podem atualizar seu próprio perfil"
  on public.perfis for update
  using (auth.uid() = id);

-- TRIGGER AUTOMÁTICO: Sempre que um usuário se cadastra no auth.users,
-- cria ou atualiza o perfil em public.perfis imediatamente (ignora RLS com privilégios security definer)
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.perfis (id, nome, telefone, endereco, numero, bairro, cidade, ponto_referencia)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', ''),
    coalesce(new.raw_user_meta_data->>'telefone', ''),
    coalesce(new.raw_user_meta_data->>'endereco', ''),
    coalesce(new.raw_user_meta_data->>'numero', ''),
    coalesce(new.raw_user_meta_data->>'bairro', ''),
    coalesce(new.raw_user_meta_data->>'cidade', 'Porto Velho - RO'),
    coalesce(new.raw_user_meta_data->>'ponto_referencia', '')
  )
  on conflict (id) do update set
    nome = excluded.nome,
    telefone = excluded.telefone,
    endereco = excluded.endereco,
    numero = excluded.numero,
    bairro = excluded.bairro,
    ponto_referencia = excluded.ponto_referencia;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update on auth.users
  for each row execute procedure public.handle_new_user();


-- 2. TABELA DE PEDIDOS (MEMÓRIA DE PEDIDOS)
create table if not exists public.pedidos (
  id bigint generated by default as identity primary key,
  codigo_pedido text not null,
  user_id uuid references auth.users on delete set null,
  nome_cliente text not null,
  telefone_cliente text not null,
  itens jsonb not null,
  valor_total numeric(10,2) not null,
  tipo_entrega text not null default 'entrega',
  endereco_entrega text,
  observacoes text,
  status text not null default 'pendente',
  criado_em timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ativar segurança em nível de linha (RLS)
alter table public.pedidos enable row level security;

-- Políticas de segurança para Pedidos
drop policy if exists "Usuários podem ver seus próprios pedidos" on public.pedidos;
create policy "Usuários podem ver seus próprios pedidos"
  on public.pedidos for select
  using (auth.uid() = user_id);

drop policy if exists "Qualquer pessoa pode registrar pedidos" on public.pedidos;
create policy "Qualquer pessoa pode registrar pedidos"
  on public.pedidos for insert
  with check (true);


-- 3. TABELA DE DEPOIMENTOS REAIS
create table if not exists public.depoimentos (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references auth.users on delete set null,
  nome text not null,
  cidade text default 'Porto Velho - RO',
  estrelas integer not null check (estrelas >= 1 and estrelas <= 5),
  comentario text not null,
  itens_comprados text[] default '{}',
  aprovado boolean not null default true,
  criado_em timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Garantir coluna itens_comprados caso a tabela já existisse
alter table public.depoimentos add column if not exists itens_comprados text[] default '{}';

-- Ativar segurança em nível de linha (RLS)
alter table public.depoimentos enable row level security;

-- Políticas de segurança para Depoimentos
drop policy if exists "Depoimentos aprovados são públicos" on public.depoimentos;
create policy "Depoimentos aprovados são públicos"
  on public.depoimentos for select
  using (aprovado = true);

drop policy if exists "Qualquer visitante ou cliente pode enviar depoimento" on public.depoimentos;
create policy "Qualquer visitante ou cliente pode enviar depoimento"
  on public.depoimentos for insert
  with check (true);

-- Índices de performance
create index if not exists idx_pedidos_user_id on public.pedidos(user_id);
create index if not exists idx_depoimentos_aprovado on public.depoimentos(aprovado, criado_em desc);

